"""Project-authored synthetic seed corpus generator.

This generator produces DETERMINISTIC (seeded) template-based text:

  * Syrian-dialect-flavored seed sentences (built from project word lists),
  * small code snippets in several languages,
  * mixed Arabic/English short passages.

Purpose: guarantee token/pattern coverage for dialect words and code in the
tiny debug corpus, independent of network availability. This content is
authored by the SYRIA AI project itself (license: Project-Authored / CC0
equivalent) and is clearly labeled synthetic — it is NOT claimed to be
natural dialect speech, and it is NOT generated by any external AI model.
"""

from __future__ import annotations

import json
import random
from datetime import datetime, timezone

LICENSE = "Project-Authored"
SOURCE = "SYRIA-AI-Project/synthetic-seed"

# --- Syrian-dialect flavored word slots (project word lists) -----------------
GREETINGS = ["مرحبا", "أهلا", "شو الأخبار", "سلام عليكم", "صباح الخير"]
QUESTIONS = ["شو رأيك", "كيف الحال", "وين كنت", "شو صار", "متى بتعود"]
TOPICS = [
    "العمل", "المدرسة", "السوق", "الجو", "المدينة", "البيت", "الطريق",
    "الحديقة", "النهار", "المشروع", "الحصاد", "القمح", "القطن", "الزيتون",
]
ADJ = ["كثير حلو", "صعب شوي", "منظم", "بسيط", "مهم", "جميل", "طويل", "سريع"]
CITIES = ["دمشق", "حلب", "حمص", "حماة", "اللاذقية", "دير الزور", "طرطوس", "السويداء", "إدلب"]
EN_WORDS = ["project", "team", "data", "model", "school", "market", "test", "report"]


def dialect_seed_docs(n_docs: int, seed: int = 7) -> list[dict]:
    rng = random.Random(seed)
    docs = []
    for i in range(n_docs):
        lines = []
        for _ in range(rng.randint(6, 10)):
            template = rng.choice(
                [
                    "{g}، {q} ب{topic}؟",
                    "{q} في {city}، {topic} {adj}.",
                    "في {city} في {topic} {adj}، و{topic} الآخر بده وقت.",
                    "{g}، اليوم كان يوم {adj} في {topic}.",
                    "هلق المدرسة في {city} بتعلمنا عن {topic}.",
                    "السوق في {city} {adj}، بس الأثمنة مرتفعة شوي.",
                ]
            )
            line = template.format(
                g=rng.choice(GREETINGS),
                q=rng.choice(QUESTIONS),
                topic=rng.choice(TOPICS),
                adj=rng.choice(ADJ),
                city=rng.choice(CITIES),
            )
            lines.append(line)
        text = "\n".join(lines)
        docs.append(
            {
                "doc_id": f"synthetic-dialect-{i:04d}",
                "title": "نص لهجي اصطناعي",
                "text": text,
                "source": SOURCE,
                "license": LICENSE,
                "license_url": None,
                "language": "ar",
                "meta": {"kind": "synthetic_seed", "flavor": "syrian-dialect-templates"},
                "retrieved_at": datetime.now(timezone.utc).isoformat(),
            }
        )
    return docs


# --- mixed Arabic/English ----------------------------------------------------
def mixed_seed_docs(n_docs: int, seed: int = 11) -> list[dict]:
    rng = random.Random(seed)
    docs = []
    for i in range(n_docs):
        lines = []
        for _ in range(rng.randint(5, 9)):
            template = rng.choice(
                [
                    "المشروع {en} بدأ اليوم في {city}.",
                    "The {en} team visited {city} today.",
                    "فريق {en} حلّل بيانات {topic} في {city}.",
                    "This report covers {topic} data for {city}.",
                    "نموذج {en} يعمل على نصوص عربية وإنجليزية معاً.",
                ]
            )
            lines.append(
                template.format(
                    en=rng.choice(EN_WORDS),
                    topic=rng.choice(TOPICS),
                    city=rng.choice(CITIES),
                )
            )
        docs.append(
            {
                "doc_id": f"synthetic-mixed-{i:04d}",
                "title": "Mixed synthetic seed",
                "text": "\n".join(lines),
                "source": SOURCE,
                "license": LICENSE,
                "license_url": None,
                "language": "mixed",
                "meta": {"kind": "synthetic_seed", "flavor": "ar-en-mixed"},
                "retrieved_at": datetime.now(timezone.utc).isoformat(),
            }
        )
    return docs


# --- code snippets ------------------------------------------------------------
CODE_TEMPLATES = [
    'def add(a, b):\n    """Return the sum of two numbers."""\n    return a + b\n\nprint(add(2, 3))\n',
    "for i in range({n}):\n    total += i * 2\nprint(f\"total = {{total}}\")\n",
    "import math\n\nvalue = math.sqrt({n}) * 3.14\nprint(value)\n",
    "SELECT id, name FROM students WHERE city = '{city}' ORDER BY name;\n",
    "function greet(name) {{\n  return `Hello ${{name}} from {city}`;\n}}\nconsole.log(greet('team'));\n",
    "#!/bin/bash\nfor f in *.txt; do\n  echo \"processing $f\"\ndone\n",
    'class Node:\n    def __init__(self, value):\n        self.value = value\n        self.next = None\n',
]


def code_seed_docs(n_docs: int, seed: int = 13) -> list[dict]:
    rng = random.Random(seed)
    docs = []
    for i in range(n_docs):
        text = rng.choice(CODE_TEMPLATES).format(
            n=rng.randint(5, 40),
            city=rng.choice(CITIES),
        )
        docs.append(
            {
                "doc_id": f"synthetic-code-{i:04d}",
                "title": "Code seed snippet",
                "text": text,
                "source": SOURCE,
                "license": LICENSE,
                "license_url": None,
                "language": "mixed",
                "meta": {"kind": "synthetic_seed", "flavor": "code"},
                "retrieved_at": datetime.now(timezone.utc).isoformat(),
            }
        )
    return docs


def write_seed_corpus(out_dir: str, counts: dict[str, int] | None = None, seed: int = 7) -> dict:
    counts = counts or {"dialect": 120, "mixed": 60, "code": 80}
    import os

    os.makedirs(out_dir, exist_ok=True)
    files = {
        "seed_dialect.jsonl": dialect_seed_docs(counts["dialect"], seed=seed),
        "seed_mixed.jsonl": mixed_seed_docs(counts["mixed"], seed=seed + 4),
        "seed_code.jsonl": code_seed_docs(counts["code"], seed=seed + 8),
    }
    written = {}
    for name, docs in files.items():
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8") as f:
            for d in docs:
                f.write(json.dumps(d, ensure_ascii=False) + "\n")
        written[name] = len(docs)
    return written


if __name__ == "__main__":
    import sys

    out = sys.argv[1] if len(sys.argv) > 1 else "data/seed_corpus"
    print(json.dumps(write_seed_corpus(out), indent=2))
